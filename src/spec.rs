//! Complete project specification — the single source of truth for scaffolding.
//!
//! A [`ProjectSpec`] is *complete*: every option that applies to the chosen
//! stack is filled in. Options the wizard skips are encoded in the type
//! (a frontend-only app has no [`BackendSpec`] at all), not as `None`.

use clap::ValueEnum;
use serde::{Deserialize, Serialize};
use strum_macros::{Display, EnumIter};

/// What kind of project to create: the `--kind` values and the wizard's
/// first question.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Display, ValueEnum)]
pub enum ProjectKind {
    /// Web application (backend, frontend or both).
    #[value(name = "web")]
    WebApp,
    /// Command-line application.
    #[value(name = "cli")]
    CliApp,
    /// Library crate.
    Library,
    /// Embedded firmware.
    Embedded,
    /// Game.
    Game,
}

/// A complete project description, ready for the template engine.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub enum ProjectSpec {
    WebApp(WebAppSpec),
    CliApp,
    Library,
    Embedded,
    Game,
}

/// Spec of a web application. The variant encodes which stacks apply.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub enum WebAppSpec {
    /// Backend only (API server).
    Backend(BackendSpec),
    /// Frontend only (SPA/WASM app or server-side templates).
    Frontend(FrontendSpec),
    /// Backend + frontend.
    Fullstack(FullstackSpec),
}

/// Backend stack, shared by backend-only and fullstack apps.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct BackendSpec {
    pub backend: Backend,
    pub database: Database,
    pub deployment: Deployment,
    pub testing: Vec<Testing>,
    pub features: Vec<Feature>,
}

/// Frontend-only app.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct FrontendSpec {
    pub frontend: Frontend,
    /// `None` for server-side template engines: they render inside whatever
    /// serves them, so there is nothing to deploy separately.
    pub deployment: Option<Deployment>,
}

/// Fullstack app: a [`BackendSpec`] plus a frontend.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct FullstackSpec {
    pub frontend: Frontend,
    pub backend: BackendSpec,
}

/// Web backend framework.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Display, Serialize, Deserialize, ValueEnum)]
#[serde(rename_all = "kebab-case")]
pub enum Backend {
    Actix,
    Axum,
    Rocket,
    Warp,
    Tide,
    Salvo,
    Gotham,
}

/// Frontend framework or template engine.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Display, Serialize, Deserialize, ValueEnum)]
#[serde(rename_all = "kebab-case")]
pub enum Frontend {
    Yew,
    Leptos,
    Seed,
    Svelte,
    React,
    Vue,
    Sauron,
    Minijinja,
    Tera,
    Askama,
    Handlebars,
}

impl Frontend {
    /// Server-side template engines have no separate deployment step.
    pub fn is_template_engine(self) -> bool {
        matches!(
            self,
            Self::Minijinja | Self::Tera | Self::Askama | Self::Handlebars
        )
    }
}

/// Database / ORM layer.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, Display, EnumIter, Serialize, Deserialize, ValueEnum,
)]
#[serde(rename_all = "kebab-case")]
pub enum Database {
    #[serde(rename = "sqlx")]
    #[value(name = "sqlx")]
    SQLx,
    Diesel,
    #[serde(rename = "sea-orm")]
    #[value(name = "sea-orm")]
    SeaORM,
    Sled,
}

/// Deployment target. Only `docker` shapes the output (Dockerfile and
/// .dockerignore); the other values stood for targets no template
/// renders and were removed — they generated byte-identical output to
/// `self-hosted`.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, Display, EnumIter, Serialize, Deserialize, ValueEnum,
)]
#[serde(rename_all = "kebab-case")]
pub enum Deployment {
    Docker,
    SelfHosted,
}

/// Testing tools. `Mock` is accepted by the CLI but rejected by the
/// wizard: no template renders mock content.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Display, Serialize, Deserialize, ValueEnum)]
#[serde(rename_all = "kebab-case")]
pub enum Testing {
    Api,
    #[serde(rename = "sqlx")]
    #[value(name = "sqlx")]
    SQLx,
    Mock,
}

/// Optional backend features.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, Display, EnumIter, Serialize, Deserialize, ValueEnum,
)]
#[serde(rename_all = "kebab-case")]
#[allow(non_camel_case_types)] // gRPC keeps its canonical casing
pub enum Feature {
    WebSockets,
    #[serde(rename = "grpc")]
    #[value(name = "grpc")]
    gRPC,
    #[serde(rename = "graph-ql")]
    GraphQL,
    RateLimiting,
    Cors,
    Auth,
}
